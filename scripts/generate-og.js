// Generates opengraph-image.tsx + twitter-image.tsx per idea route and injects canonical URLs into idea metadata.
const fs = require('fs');
const path = require('path');
const root = process.argv[2];
const reg = fs.readFileSync(path.join(root, 'src/data/ideas.ts'), 'utf8');

// var name -> hero path relative to src/app
const heroByVar = {};
for (const m of reg.matchAll(/^import (\w+) from "@\/app\/(.+)";$/gm)) heroByVar[m[1]] = m[2];

const entries = [];
for (const m of reg.matchAll(/slug: "([^"]+)",[\s\S]*?title: "([^"]+)",[\s\S]*?image: (\w+),\s*\n\s*href: "\/([^"]+)"/g)) {
    entries.push({ slug: m[1], title: m[2], hero: heroByVar[m[3]], route: m[4] });
}
if (entries.length !== 33) throw new Error('expected 33 ideas, got ' + entries.length);

const ogFile = (e) => `import { renderIdeaOg, OG_SIZE } from "@/lib/og/render";

// Generated by scripts/generate-og.js. Branded share card for this idea.
export const alt = ${JSON.stringify(`${e.title} | AGI Futures startup idea`)};
export const size = OG_SIZE;
export const contentType = "image/png";

export default function Image() {
    return renderIdeaOg(${JSON.stringify(e.slug)}, ${JSON.stringify(e.hero)});
}
`;

let canon = 0, skipped = [];
for (const e of entries) {
    const dir = path.join(root, 'src/app', e.route);
    fs.writeFileSync(path.join(dir, 'opengraph-image.tsx'), ogFile(e));
    fs.writeFileSync(path.join(dir, 'twitter-image.tsx'), ogFile(e));

    const pagePath = path.join(dir, 'page.tsx');
    let page = fs.readFileSync(pagePath, 'utf8');
    if (page.includes('alternates')) continue;
    const re = /export const metadata(: Metadata)? = \{\r?\n/;
    if (re.test(page)) {
        page = page.replace(re, (s) => `${s}    alternates: { canonical: '/${e.route}' },\n`);
        fs.writeFileSync(pagePath, page);
        canon++;
    } else skipped.push(e.route);
}
console.log(`og files: ${entries.length * 2}, canonicals added: ${canon}, needs manual: ${skipped.join(', ') || 'none'}`);
